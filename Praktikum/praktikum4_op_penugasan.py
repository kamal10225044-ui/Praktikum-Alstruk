# 1. Simpan poin awal dalam variabel poin. 
# 2. Tambahkan 25 poin menggunakan +=. 
# 3. Kurangi 10 poin menggunakan -=. 
# 4. Kalikan poin dengan 2 menggunakan *=. 
# 5. Bagi poin dengan 2 menggunakan /=. 

poin = 100
print(f"Poin awal: {poin}")
poin += 25
print(f"Poin += 25: {poin}")
poin -= 10
print(f"Poin -= 10: {poin}")
poin *= 2
print(f"Poin *= 2: {poin}")
poin /= 2
print(f"Poin /= 2: {poin}")